import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { loadRuntime } from "./load_runtime.mjs";
const ctx = loadRuntime(["base.js", "roteiro.js", "alinhamento.js"]);
const { BQ } = ctx;
const REF = "C:/app.Modelar-Concorrentes-MKT/house/videos/reboco-novo/assets";
const ref = JSON.parse(readFileSync(`${REF}/transcript.json`, "utf8"));
const SP = { "1.": "um", "2.": "dois", "3.": "três", "28": "vinte e oito", "13,": "treze", "1": "um", "13245": "treze mil duzentos e quarenta e cinco", "NBR": "ene bê erre", "pH": "pê agá", "House": "ráus", "WhatsApp.": "uótsap" };
const text = "# gancho\n" + ref.map((w) => SP[w.text] ? `{${w.text.replace(/[.,]$/, "")}|${SP[w.text]}}${(w.text.match(/[.,]$/) || [""])[0]}` : w.text).join(" ");
const parsed = BQ.roteiro.parse(text);
console.log("tokens", parsed.tokens.length, "erros", parsed.errors, "avisos", parsed.warnings.length);
const raw = execFileSync("ffmpeg", ["-v", "error", "-i", `${REF}/narracao-norm.mp3`, "-ac", "1", "-ar", "16000", "-f", "f32le", "-"], { maxBuffer: 1 << 28 });
const s = new Float32Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
const r = BQ.align.align(s, 16000, parsed.tokens);
const e = r.words.map((w, i) => Math.abs(w.start - ref[i].start)).sort((a, b) => a - b);
console.log("mediana", e[Math.floor(e.length / 2)].toFixed(3), "p90", e[Math.floor(e.length * 0.9)].toFixed(3), "max", e[e.length - 1].toFixed(3));
const est = BQ.roteiro.estimate(parsed);
console.log("duração estimada", est.words[est.words.length - 1].end.toFixed(1), "s · real", ref[ref.length - 1].end);
const built = BQ.roteiro.build(parsed, { words: r.words, voiceDuration: 71.1, source: "voz" });
console.log("C.end", built.C.end, "legendas", BQ.roteiro.captionGroups(built.words).length);
